"""HTTP layer for estimates: request/response contracts and error mapping. No business logic here."""

import logging
from datetime import datetime, timezone

import openai
from fastapi import APIRouter, HTTPException
from pydantic import BaseModel, ConfigDict, Field

from app.services.llm_service import generate_estimation

logger = logging.getLogger(__name__)

router = APIRouter(tags=["estimations"])


class EstimationRequest(BaseModel):
    # Strip spaces first, so a text of only spaces counts as empty and gets a 422.
    model_config = ConfigDict(str_strip_whitespace=True)

    transcription: str = Field(
        min_length=1,
        max_length=20_000,  # cap the size of one call (cost and context window)
        description="Text of the meeting transcript to estimate.",
        examples=["In the meeting, the client explained that they need a landing page with..."],
    )


class EstimationResponse(BaseModel):
    estimation: str = Field(description="The estimate generated by the LLM, in Markdown.")
    model: str = Field(description="Exact model version that answered, e.g. gpt-4o-mini-2024-07-18.")
    provider: str
    input_tokens: int
    output_tokens: int
    created_at: datetime


@router.post("/estimate", response_model=EstimationResponse)
async def create_estimation(request: EstimationRequest) -> EstimationResponse:
    try:
        result = await generate_estimation(request.transcription)
    except openai.OpenAIError as exc:
        # Upstream failure (no credit, bad key, network): 502, with no internal details for the caller.
        logger.error("LLM call failed: %s", type(exc).__name__)
        raise HTTPException(status_code=502, detail="The LLM provider failed. Try again later.") from exc

    return EstimationResponse(
        estimation=result.estimation,
        model=result.model,
        provider=result.provider,
        input_tokens=result.input_tokens,
        output_tokens=result.output_tokens,
        created_at=datetime.now(timezone.utc),
    )
