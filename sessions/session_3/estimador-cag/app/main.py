"""FastAPI application: wires the routers, the health probe and the API docs."""

import logging

from fastapi import FastAPI

from app.config import get_settings
from app.routers import estimations

# Fail fast: load the settings at start-up, so a missing or empty API key stops the server
# immediately with a clear message instead of failing on the first request.
settings = get_settings()

logging.basicConfig(level=settings.log_level.upper())

app = FastAPI(
    title="CAG Software Estimator",
    description=(
        "Receives the transcript of a client meeting and returns a software estimate "
        "generated by an LLM. CAG architecture: past estimates travel as static context "
        "inside every prompt (no database, no retrieval)."
    ),
    version="0.1.0",
)

app.include_router(estimations.router, prefix="/api/v1")


@app.get("/health", tags=["health"])
async def health() -> dict[str, str]:
    """Service status. Never calls the LLM, so it is free and fast."""
    return {"status": "ok", "provider": settings.llm_provider, "model": settings.llm_model}
